//go:build small

package main

import (
	"go/parser"
	"go/token"
	"reflect"
	"testing"
)

func TestComments(t *testing.T) {
	tests := []struct {
		name   string
		path   string
		source string
		want   []string
	}{
		{name: "when Comments with no comment then returns nothing", path: "x.go", source: "package x\nfunc f() {}\n", want: nil},
		{name: "when Comments with a line comment then returns it", path: "x.go", source: "package x\n// f does things\nfunc f() {}\n", want: []string{"// f does things"}},
		{name: "when Comments with a block comment then returns it", path: "x.go", source: "package x\n/* f */\nfunc f() {}\n", want: []string{"/* f */"}},
		{name: "when Comments with a build constraint then returns nothing", path: "x.go", source: "//go:build small\n\npackage x\n", want: nil},
		{name: "when Comments with a lint exception then returns nothing", path: "x.go", source: "package x\nfunc f() {} //nolint:errcheck // reason\n", want: nil},
		{name: "when Comments with a line directive then returns nothing", path: "x.go", source: "package x\n//line a.go:1\nfunc f() {}\n", want: nil},
		{name: "when Comments with a sum type declaration then returns nothing", path: "x.go", source: "package x\n//sumtype:decl\ntype S interface{ s() }\n", want: nil},
		{name: "when Comments with a directive-like prefix then returns it", path: "x.go", source: "package x\n// go:build\nfunc f() {}\n", want: []string{"// go:build"}},
		{name: "when Comments with a generated file then returns nothing", path: "x.go", source: "// Code generated by x. DO NOT EDIT.\n\npackage x\n// f\nfunc f() {}\n", want: nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file, err := parser.ParseFile(token.NewFileSet(), tt.path, tt.source, parser.ParseComments|parser.SkipObjectResolution)
			if err != nil {
				t.Fatal(err)
			}

			var got []string
			for _, c := range Comments(file) {
				got = append(got, c.Text)
			}

			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("got %v, want %v", got, tt.want)
			}
		})
	}
}
